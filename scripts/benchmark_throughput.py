"""How many invoices an hour the desk handles on this machine (round 3, idea 8).

    python -m scripts.benchmark_throughput --n 200            # print the figures
    python -m scripts.benchmark_throughput --n 200 --write    # also write docs/throughput.md

Text PDFs of generated layouts (scripts/generate_test_data.variant_spec), each billing a
purchase order that is added to the register the way scripts/evaluate_extraction.py does.
The PDFs are drawn before the clock starts; only the pipeline run is timed. All invoices go
into one set of books, as a day's inbox would, with the AI assist off.
"""
from __future__ import annotations

import argparse
import platform
import shutil
import statistics
import sys
import tempfile
import time
from pathlib import Path

from invoice_desk import config
from invoice_desk.llm import LlmAssist
from invoice_desk.masterdata import load_master
from invoice_desk.pipeline import Pipeline
from invoice_desk.rules import load_rules
from invoice_desk.store import Store
from scripts import generate_test_data as G
from scripts.evaluate_extraction import matching_po

REPORT = config.ROOT / "docs" / "throughput.md"
MONTHLY, WORKING_DAYS, HOURS_A_DAY = 10_000, 22, 8


def build(n: int) -> list[tuple[str, bytes, dict, dict]]:
    """n generated invoices whose purchase order numbers do not collide."""
    out, seen, index = [], set(), 0
    while len(out) < n:
        spec = G.variant_spec(index)
        index += 1
        truth = G.truth_for(spec)
        if truth["po_ref"] in seen:
            continue
        seen.add(truth["po_ref"])
        out.append((spec["id"], G.render_invoice_pdf(spec), spec, truth))
    return out


def measure(n: int) -> dict:
    invoices = build(n)
    master = load_master().model_copy(deep=True)
    for _, _, spec, truth in invoices:
        master.pos[truth["po_ref"]] = matching_po(spec, truth)
    folder = Path(tempfile.mkdtemp(prefix="invoice_desk_throughput_"))
    try:
        pipeline = Pipeline(store=Store(folder / "books.db"), rules=load_rules(), master=master,
                            llm=LlmAssist(config.LlmConfig(mode="off")), today=G.date(2026, 11, 21), ocr_mode="fixture")
        seconds, verdicts = [], {}
        started = time.perf_counter()
        for name, pdf, _, _ in invoices:
            t0 = time.perf_counter()
            result = pipeline.run(pdf, f"{name}.pdf", "benchmark")
            seconds.append(time.perf_counter() - t0)
            verdicts[result.verdict] = verdicts.get(result.verdict, 0) + 1
        total = time.perf_counter() - started
    finally:
        shutil.rmtree(folder, ignore_errors=True)
    ordered = sorted(seconds)
    p95 = ordered[min(len(ordered) - 1, max(0, round(0.95 * len(ordered)) - 1))]
    return {"n": n, "total": total, "median": statistics.median(seconds), "p95": p95,
            "per_hour": n / total * 3600 if total else 0.0, "verdicts": verdicts}


def lines(m: dict) -> list[str]:
    needed = MONTHLY / (WORKING_DAYS * HOURS_A_DAY)
    verdicts = ", ".join(f"{k} {v}" for k, v in sorted(m["verdicts"].items()))
    return [f"{m['n']} invoices (text PDFs) in {m['total']:.1f} seconds on one process: {verdicts}.",
            f"Per invoice: median {m['median'] * 1000:.0f} ms, 95th percentile {m['p95'] * 1000:.0f} ms.",
            f"About {m['per_hour']:,.0f} invoices an hour.",
            f"{MONTHLY:,} a month is about {needed:.0f} an hour over {WORKING_DAYS} working days of {HOURS_A_DAY} hours."]


def report(m: dict) -> str:
    body = "\n".join(f"- {line}" for line in lines(m))
    return f"""# Throughput

Generated by `python -m scripts.benchmark_throughput --n {m['n']} --write` on {platform.system()} {platform.release()},
Python {platform.python_version()}, measured {config.now_utc().date().isoformat()}.

{body}

## How it was measured

Generated text invoices with layouts the reader was not tuned on, each billing a purchase order added to the
register. The PDFs are drawn before the clock starts; the time is the pipeline run only (all nine stages, the
ledger write and the audit receipt). One set of books, one process, the AI assist off.

## What limits it

- Scanned pages are slower: each page is straightened and read twice by OCR. Expect seconds per page, not
  milliseconds; run `python -m scripts.evaluate_extraction` for scan timings.
- SQLite takes one writer at a time, so more processes on the same books would queue. At scale the store moves to a
  database with concurrent writers and a job queue keyed by the file fingerprint, which the design already uses to
  make a repeated file harmless.
- An AI assist call adds a network round trip of a second or more, for the few invoices that need it.
- The real limit is people: every hold needs a person, so the share that passes untouched decides the staffing.
"""


def main(argv: list[str] | None = None) -> int:
    for stream in (sys.stdout, sys.stderr):
        try:
            stream.reconfigure(encoding="utf-8", errors="replace")
        except (AttributeError, ValueError):
            pass
    parser = argparse.ArgumentParser(description="Measure invoices per hour on this machine.")
    parser.add_argument("--n", type=int, default=200, help="how many invoices (default 200)")
    parser.add_argument("--write", action="store_true", help="also write docs/throughput.md")
    args = parser.parse_args(argv)
    if args.n < 1:
        parser.error("--n must be at least 1")
    m = measure(args.n)
    print("\n".join(lines(m)))
    if args.write:
        REPORT.write_text(report(m), encoding="utf-8", newline="\n")
        print(f"wrote {REPORT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
